"""
js_output.py
------------
Writes processed data as a JavaScript constant (const NAME = {...};) so the
web page can load it with a <script> tag and works when opened from disk
(browsers block fetch() for local files).
"""

import json


def write_js(path, variable, payload, generator):
    """Write data as a JavaScript constant so the page works from disk."""
    with open(path, "w", encoding="utf-8") as out:
        out.write(f"// Generated by processing/{generator}. Do not edit by hand.\n")
        out.write(f"const {variable} = ")
        json.dump(payload, out, ensure_ascii=False)
        out.write(";\n")
